export function getTranslation(key: string, lang: LanguageCode = 'en', fallback?: string): string {
  const entry = TRANSLATIONS[key];
  if (entry && entry[lang]) {
    return entry[lang];
  }
  if (entry && entry.en) {
    return entry.en;
  }
  return fallback || key;
}
